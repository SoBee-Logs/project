const FALLBACK = ['#6c63ff', '#f857a6', '#0ea5e9', '#10b981', '#f59e0b', '#8b5cf6', '#ec4899', '#14b8a6', '#ef4444', '#64748b', '#f97316', '#84cc16', '#06b6d4', '#a855f7', '#d946ef']

// 카테고리명으로 고정 색을 반환. 매핑에 없으면 인덱스 기반 fallback 색.
export function categoryColor(name, i = 0) {
  return CATEGORY_COLORS[name] || FALLBACK[i % FALLBACK.length]
}
